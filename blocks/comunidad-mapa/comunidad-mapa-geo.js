function regionOf(lat, lon) {
  if (lat > 59 && lon >= -75 && lon < -10) return 'greenland';
  if (lon < -30) return lat >= 15 ? 'northAmerica' : 'southAmerica';
  if (lon < 60) return 'eurafrica';
  if (lat < -11) return 'oceania';
  if (lon >= 100 && lat >= 20 && lat < 50) return 'eastAsia';
  if (lon >= 90 && lat < 20) return 'southeastAsia';
  return 'asia';
}

const isInside = ([x, y]) => x >= 0 && x <= 100 && y >= 0 && y <= 100;

/**
 * Converts latitude/longitude to a position on world-dots.svg.
 * @param {number} lat Latitude
 * @param {number} lon Longitude
 * @param {boolean} clip Return null when the position falls outside the map
 * @returns {[number, number]|null} [x%, y%] of the map image
 */
export function toMapPercent(lat, lon, clip = true) {
  const [xScale, xOffset, yScale, yOffset] = REGIONS[regionOf(lat, lon)];
  const position = [xScale * lon + xOffset, yOffset - yScale * lat];
  return !clip || isInside(position) ? position : null;
}

/**
 * Position of a country on the map, with the artistic-map adjustment if it has one.
 * @param {string} code ISO 3166-1 alpha-2 code
 * @returns {[number, number]|null} [x%, y%], or null if unknown or outside the map
 */
export function countryPosition(code) {
  const coords = COUNTRY_COORDS[code];
  if (!coords) return null;
  const [x, y] = toMapPercent(coords[0], coords[1], false);
  const [dx, dy] = ADJUSTMENTS[code] || [0, 0];
  const position = [x + dx, y + dy];
  return isInside(position) ? position : null;
}
